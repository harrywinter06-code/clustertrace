"""Generate self-contained shareable HTML trace snapshots.

`agentlog snapshot <trace_id>` produces a single HTML file embedding both
trace data and a small renderer — no server, no external assets, no JS
build step. The file is portable: email it, drop it in a PR, attach to
a bug report.
"""
from __future__ import annotations

import html
import json
from typing import Any

from agentlog import cost as cost_mod
from agentlog import storage

