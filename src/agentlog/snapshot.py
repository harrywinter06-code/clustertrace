def _esc(s: Any) -> str:
    return html.escape("" if s is None else str(s), quote=False)


def _fmt_pre(obj: Any) -> str:
    if obj is None:
        return ""
    try:
        return _esc(json.dumps(obj, indent=2, default=str))
    except (TypeError, ValueError):
        return _esc(repr(obj))


def render(trace_id: str) -> str:
    """Build the self-contained HTML string for a trace."""
    with storage.connect() as conn:
        trace = conn.execute("SELECT * FROM traces WHERE id = ?", (trace_id,)).fetchone()
        if trace is None:
            raise KeyError(f"trace not found: {trace_id}")
        spans = conn.execute(
            "SELECT * FROM spans WHERE trace_id = ? ORDER BY started_at",
            (trace_id,),
        ).fetchall()
        tags = dict(conn.execute(
            "SELECT key, value FROM trace_tags WHERE trace_id = ?", (trace_id,)
        ).fetchall())
        metrics = dict(conn.execute(
            "SELECT name, value FROM trace_metrics WHERE trace_id = ?", (trace_id,)
        ).fetchall())

    title = _esc(trace["name"])
    duration_ms = (
        round((trace["ended_at"] - trace["started_at"]) * 1000, 1)
        if trace["ended_at"] else None
    )
    cost = trace["cost_usd"] if "cost_usd" in trace.keys() else None
    meta_bits = [
        f'<span class="badge {trace["status"]}">{trace["status"]}</span>',
        f'{duration_ms} ms' if duration_ms is not None else 'in-flight',
        f'{len(spans)} spans',
    ]
    if cost is not None:
        meta_bits.append(f'${cost:.4f}')
    if trace["error_type"]:
        meta_bits.append(f'<span class="err">{_esc(trace["error_type"])}: {_esc(trace["error_message"] or "")}</span>')
    meta = " · ".join(meta_bits)

    tags_html = " ".join(f'<span class="tag-chip">{_esc(k)}={_esc(v)}</span>' for k, v in tags.items()) or '<span class="muted small">no tags</span>'
    metrics_html = " ".join(f'<span class="tag-chip">{_esc(k)}={v:.3f}</span>' for k, v in metrics.items()) or ""

    t0 = trace["started_at"]
    t1 = trace["ended_at"] or (max((s["ended_at"] or s["started_at"]) for s in spans) if spans else t0)
    total = max(t1 - t0, 0.001)
    timeline_html = ""
    for s in spans:
        start_pct = (s["started_at"] - t0) / total * 100
        end_pct = ((s["ended_at"] or t1) - t0) / total * 100
        width = max(end_pct - start_pct, 0.5)
        s_dur = round((s["ended_at"] - s["started_at"]) * 1000, 1) if s["ended_at"] else None
        timeline_html += f'''
        <div class="tl-row">
          <div class="tl-label">{_esc(s["name"])} <span class="muted small">[{_esc(s["kind"])}]</span></div>
          <div class="tl-bar-wrap"><div class="tl-bar {s["status"]}" style="left:{start_pct:.2f}%;width:{width:.2f}%"></div></div>
          <div class="muted small" style="text-align:right;">{s_dur if s_dur is not None else "—"} ms</div>
        </div>'''

    spans_html = ""
    for s in spans:
        attrs = json.loads(s["attrs_json"]) if s["attrs_json"] else None
        # If we have a cached cost on this span, surface it.
        s_cost = s["cost_usd"] if "cost_usd" in s.keys() else None
        if s_cost is None and attrs:
            s_cost = cost_mod.estimate_span_cost(attrs)
        cost_chip = f' <span class="tag-chip">${s_cost:.5f}</span>' if s_cost is not None else ""
        inp = json.loads(s["input_json"]) if s["input_json"] else None
        out = json.loads(s["output_json"]) if s["output_json"] else None
        spans_html += f'''
        <details class="span-card {s["status"]}" {"open" if s["status"] == "error" else ""}>
          <summary>
            <span class="kind">{_esc(s["kind"])}</span>
            <span style="font-weight:500;">{_esc(s["name"])}</span>
            <span class="muted small">{round((s["ended_at"] - s["started_at"])*1000, 1) if s["ended_at"] else "—"} ms</span>
            <span class="badge {s["status"]}">{s["status"]}</span>
            {cost_chip}
          </summary>
          {f'<div class="err"><b>{_esc(s["error_type"])}:</b> {_esc(s["error_message"] or "")}</div>' if s["error_type"] else ""}
          <div class="io">
            {f"<div><h4>Input</h4><pre>{_fmt_pre(inp)}</pre></div>" if inp else ""}
            {f"<div><h4>Output</h4><pre>{_fmt_pre(out)}</pre></div>" if out else ""}
            {f"<div><h4>Attrs</h4><pre>{_fmt_pre(attrs)}</pre></div>" if attrs else ""}
          </div>
        </details>'''

    return _TEMPLATE.format(
        title=title,
        meta=meta,
        tags_html=tags_html,
        metrics_html=metrics_html,
        timeline_html=timeline_html,
        n_spans=len(spans),
        spans_html=spans_html,
    )
